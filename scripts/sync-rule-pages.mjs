#!/usr/bin/env node
// Usage: node scripts/sync-rule-pages.mjs
//
// Copies prose from the rule pages into generated data files, so packages that cannot read
// files at run time still speak in pbiplint's own words:
//   packages/core/src/rules/rule-summaries.data.ts  the first paragraph of "What it checks",
//                                                    which becomes Rule.description
//   packages/cli/src/rule-help.data.ts               the Why, How to fix, and Quirks sections plus
//                                                    a link to the page, which the CLI hands to the
//                                                    SARIF formatter as each rule's help block
// The rule-pages tests fail when a data file and the pages disagree.
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const SUMMARIES_OUT = "packages/core/src/rules/rule-summaries.data.ts";
const HELP_OUT = "packages/cli/src/rule-help.data.ts";
const RULE_URL_BASE = "https://pbiplint.com/rules/";

/** The page's `## ` sections by heading, frontmatter and title dropped. */
const sections = (text) => {
  const body = text.replace(/^---\n[\s\S]*?\n---\n/, "");
  const out = {};
  for (const chunk of body.split(/^## /m).slice(1)) {
    const nl = chunk.indexOf("\n");
    out[chunk.slice(0, nl).trim()] = chunk.slice(nl + 1).trim();
  }
  return out;
};

const firstParagraph = (s) =>
  s
    .trim()
    .split(/\n\s*\n/)[0]
    ?.replace(/\s+/g, " ")
    .trim() ?? "";

/** Markdown help for SARIF consumers: the page minus its What section, plus a link back. */
const helpMarkdown = (s, url) =>
  [
    "### Why it matters",
    "",
    s["Why it matters"],
    "",
    "### How to fix it",
    "",
    s["How to fix it"],
    ...(s["Quirks"] ? ["", "### Quirks", "", s["Quirks"]] : []),
    "",
    `Read more: ${url}`,
  ].join("\n");

/** The same help as plain text: headings kept as lines, code fences and backticks dropped. */
const helpText = (markdown) =>
  markdown
    .split("\n")
    .filter((line) => !/^```/.test(line))
    .map((line) => line.replace(/^### /, ""))
    .join("\n")
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, "$1 ($2)")
    .replace(/`/g, "");

const summaries = {};
const help = {};
for (const file of readdirSync("rules")
  .filter((f) => f.endsWith(".md"))
  .sort()) {
  const text = readFileSync(`rules/${file}`, "utf8");
  const frontmatter = /^---\n([\s\S]*?)\n---\n/.exec(text)?.[1] ?? "";
  const id = /^id: (.+)$/m.exec(frontmatter)?.[1]?.trim();
  if (!id) throw new Error(`${file}: no id in frontmatter`);
  const s = sections(text);
  for (const heading of ["What it checks", "Why it matters", "How to fix it"])
    if (!s[heading] || s[heading].startsWith("TODO"))
      throw new Error(`${file}: "${heading}" is not written`);
  summaries[id] = firstParagraph(s["What it checks"]);
  const markdown = helpMarkdown(s, RULE_URL_BASE + file.replace(/\.md$/, ""));
  help[id] = { text: helpText(markdown), markdown };
}

writeFileSync(
  SUMMARIES_OUT,
  `// Generated by scripts/sync-rule-pages.mjs from the first paragraph of each rule page's
// "What it checks" section. Do not edit by hand: edit the page under rules/ and rerun the script.

/** What each rule checks, one paragraph in pbiplint's own words, keyed by rule id. */
export const RULE_SUMMARIES: Readonly<Record<string, string>> = ${JSON.stringify(summaries, null, 2)};
`,
);
writeFileSync(
  HELP_OUT,
  `// Generated by scripts/sync-rule-pages.mjs from the Why, How to fix, and Quirks sections of each
// rule page. Do not edit by hand: edit the page under rules/ and rerun the script.
import type { RuleHelp } from "@pbiplint/core";

/** SARIF help per rule id: the page's Why, How to fix, and Quirks, plus a link to the page. */
export const RULE_HELP: Readonly<Record<string, RuleHelp>> = ${JSON.stringify(help, null, 2)};
`,
);
execFileSync("node_modules/.bin/prettier", ["--write", SUMMARIES_OUT, HELP_OUT], {
  stdio: "ignore",
});
console.log(
  `wrote ${Object.keys(summaries).length} summaries to ${SUMMARIES_OUT} and ${Object.keys(help).length} help entries to ${HELP_OUT}`,
);
