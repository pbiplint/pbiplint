import { describe, expect, it } from "vitest";
import { fingerprint as coreFingerprint } from "../../packages/core/src/custom-rules/te/fingerprint.ts";
import { readTeRuleFile } from "../../packages/core/src/custom-rules/te/read.ts";
import {
  dataFile,
  fingerprint,
  fingerprintVersions,
  readRules,
} from "../fingerprint-upstream-rules.mjs";

describe("fingerprint", () => {
  it("agrees with core's", () => {
    for (const s of [
      "",
      "a",
      "foobar",
      'Name.Contains("Total")\r\n\tand  IsHidden',
      "Größe\u00a0日付\u2003a😀b",
      "a\u200bb\u0085c\u000bd",
      // A lone surrogate, which both write as U+FFFD.
      'Name.Contains("\ud83d")',
      "\ude00 x \ud800",
      // Whitespace inside a string literal is kept, a doubled quote staying inside it.
      'Name.EndsWith( " Flag" )',
      'Name.Contains(" ")\n  and Name <> "a "" b "',
      'Name == " unclosed',
    ])
      expect(fingerprint(s), JSON.stringify(s)).toBe(coreFingerprint(s));
  });
});

describe("readRules", () => {
  it("reads a rule list, a rules wrapper, and a file of one rule", () => {
    const one = { ID: "A", Scope: "Model", Expression: "true" };
    for (const text of [
      JSON.stringify([one]),
      JSON.stringify({ rules: [one] }),
      JSON.stringify(one),
    ])
      expect(readRules(text, readTeRuleFile).map((r) => r.id)).toEqual(["A"]);
    expect(readRules("not json", readTeRuleFile)).toEqual([]);
  });
});

describe("fingerprintVersions", () => {
  const ids = new Map([
    ["TEAM_A", "TEAM_A"],
    ["TEAM_B", "TEAM_B"],
  ]);
  const v1 = JSON.stringify([
    { ID: "team_a", Scope: "Measure, CalculatedColumn", Severity: 1, Expression: 'Name == "x"' },
    { ID: "TEAM_B", Scope: "DataColumn", Expression: 'Name <> "y"' },
    { ID: "TEAM_ONLY", Scope: "Model", Severity: 3, Expression: "true" },
    { ID: "TEAM_B", Expression: "no scope, so the reader cannot read it" },
  ]);
  // The next version reflows one rule (same fingerprint) and raises the other's severity.
  const v2 = `\uFEFF// a comment\n${JSON.stringify([
    { ID: "TEAM_A", Scope: "CalculatedColumn,Measure", Severity: 1, Expression: 'Name  ==\n  "x"' },
    { ID: "TEAM_B", Scope: "DataColumn", Severity: 2, Expression: 'Name <> "y"' },
  ])}`;

  it("keeps the built-in ids, one entry per distinct version, sorted", () => {
    const entries = fingerprintVersions([{ text: v1 }, { text: v2 }], ids, readTeRuleFile);
    expect(entries).toEqual([
      {
        id: "TEAM_A",
        scope: "CalculatedColumn,Measure",
        hash: fingerprint('Name=="x"'),
        severity: 1,
      },
      { id: "TEAM_B", scope: "DataColumn", hash: fingerprint('Name<>"y"'), severity: 1 },
      { id: "TEAM_B", scope: "DataColumn", hash: fingerprint('Name<>"y"'), severity: 2 },
    ]);
    for (const e of entries)
      expect(Object.keys(e).sort()).toEqual(["hash", "id", "scope", "severity"]);
  });
});

describe("dataFile", () => {
  it("writes a header naming each source and version, then one entry per fingerprint", () => {
    const source = {
      repository: "example/rules",
      commit: "0123456789abcdef0123456789abcdef01234567",
      license: "MIT",
    };
    const versions = [
      { path: "rules/a.json", commit: "aaaaaaaaaaaaaaaaaaaa", sha256: "1".repeat(64) },
      { path: "rules/b.json", commit: "bbbbbbbbbbbbbbbbbbbb", sha256: "2".repeat(64) },
    ];
    const entries = [
      { id: "TEAM_A", scope: "Measure", hash: "0123456789abcdef", severity: 2 },
      { id: "TEAM_B", scope: "CalculatedColumn,DataColumn", hash: "fedcba9876543210", severity: 1 },
    ];
    const text = dataFile([{ source, versions }], entries);
    expect(text.startsWith("// Generated by scripts/fingerprint-upstream-rules.mjs.")).toBe(true);
    expect(text).toContain(
      [
        `// example/rules, read up to commit ${source.commit} (license: MIT),`,
        "// 2 file versions, by sha256, path, and a commit that holds it:",
        `//   ${"1".repeat(64)} rules/a.json @ aaaaaaaaaaaa`,
        `//   ${"2".repeat(64)} rules/b.json @ bbbbbbbbbbbb`,
        "",
        "export interface UpstreamRule {",
      ].join("\n"),
    );
    expect(
      text.endsWith(`export const UPSTREAM_RULES: readonly UpstreamRule[] = [
  {
    id: "TEAM_A",
    scope: "Measure",
    hash: "0123456789abcdef",
    severity: 2,
  },
  {
    id: "TEAM_B",
    scope: "CalculatedColumn,DataColumn",
    hash: "fedcba9876543210",
    severity: 1,
  },
];
`),
    ).toBe(true);
  });
});
