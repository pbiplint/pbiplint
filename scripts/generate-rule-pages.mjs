// Microsoft writes list-like descriptions ("Option 1: ... \n Option 2: ...") with single newlines,
// which Markdown collapses into one paragraph. Every surviving line becomes its own paragraph, so a
// run of blank lines collapses to the single blank line that separates two paragraphs.
const why = (rule) => {
  const text = rule.description
    .split("\n")
    .filter((line) => !/^\s*Reference:/i.test(line))
    .map((line) => line.trim())
    .filter((line) => line.length > 0)
    .join("\n\n");
  return text.length
    ? text
    : `Microsoft's Best Practice Analyzer includes this rule under ${rule.category}.`;
};

mkdirSync("rules", { recursive: true });
let written = 0;
for (const rule of defaultRules) {
  const path = `rules/${slug(rule.id)}.md`;
  if (existsSync(path) && !force) continue;
  const summary = SUMMARIES[rule.id];
  if (!summary) throw new Error(`No summary for ${rule.id}`);
  const [what, fix] = summary;
  const sources = rule.status === "builtin" ? rule.references : [RULESET_URL, ...rule.references];
  const lines = [
    "---",
    `id: ${rule.id}`,
    `name: ${JSON.stringify(rule.name)}`,
    `category: ${rule.category}`,
    `severity: ${SEVERITY_LABEL[rule.severity]}`,
    `scope: [${rule.scope.join(", ")}]`,
    `status: ${rule.status}`,
    "video:",
    "sources:",
    ...sources.map((u) => `  - ${u}`),
    "---",
    "",
    `# ${rule.name}`,
    "",
    "## What it checks",
    "",
    what,
    "",
    "## Why it matters",
    "",
    why(rule),
    "",
    "## How to fix it",
    "",
    fix,
    ...(rule.fixExpression ? ["", `Tabular Editor fix expression: \`${rule.fixExpression}\``] : []),
    ...(rule.status === "needsLiveModel"
      ? [
          "",
          "pbiplint cannot evaluate this rule from files; it appears in `pbiplint rules` as needing a live model.",
        ]
      : []),
    "",
  ];
  const quirks = QUIRKS[rule.id];
  if (quirks) lines.push("## Quirks", "", ...quirks.map((q) => `- ${q}`), "");
  lines.push("## Links", "", ...sources.map((u) => `- ${u}`), "");
  writeFileSync(path, lines.join("\n"));
  written++;
}
console.log(`wrote ${written} rule page(s)`);
