#!/usr/bin/env node
// Usage: node scripts/sync-rule-summaries.mjs
//
// Copies the first paragraph of every rule page's "What it checks" section into
// packages/core/src/rules/rule-summaries.data.ts, so the core package (which cannot read files)
// carries pbiplint's own one-paragraph description of each rule for tool output such as SARIF.
// The rule-pages test fails when the data file and the pages disagree.
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const OUT = "packages/core/src/rules/rule-summaries.data.ts";
const summaries = {};
for (const file of readdirSync("rules")
  .filter((f) => f.endsWith(".md"))
  .sort()) {
  const text = readFileSync(`rules/${file}`, "utf8");
  const frontmatter = /^---\n([\s\S]*?)\n---\n/.exec(text)?.[1] ?? "";
  const id = /^id: (.+)$/m.exec(frontmatter)?.[1]?.trim();
  if (!id) throw new Error(`${file}: no id in frontmatter`);
  const section = text.split("## What it checks")[1]?.split(/\n## /)[0] ?? "";
  const paragraph =
    section
      .trim()
      .split(/\n\s*\n/)[0]
      ?.replace(/\s+/g, " ")
      .trim() ?? "";
  if (!paragraph || paragraph.startsWith("TODO"))
    throw new Error(`${file}: What it checks is not written`);
  summaries[id] = paragraph;
}

const out = `// Generated by scripts/sync-rule-summaries.mjs from the first paragraph of each rule page's
// "What it checks" section. Do not edit by hand: edit the page under rules/ and rerun the script.

/** What each rule checks, one paragraph in pbiplint's own words, keyed by rule id. */
export const RULE_SUMMARIES: Readonly<Record<string, string>> = ${JSON.stringify(summaries, null, 2)};
`;
writeFileSync(OUT, out);
execFileSync("node_modules/.bin/prettier", ["--write", OUT], { stdio: "ignore" });
console.log(`wrote ${Object.keys(summaries).length} summaries to ${OUT}`);
