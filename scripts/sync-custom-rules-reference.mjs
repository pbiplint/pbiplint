#!/usr/bin/env node
// Usage: npm run build -w @pbiplint/core && node scripts/sync-custom-rules-reference.mjs
//
// Writes the reference on the site's custom rules page, everything a Tabular Editor rule can use
// in pbiplint and what it cannot, from the built core's teReference(), which builds it from the
// evaluator's own tables:
//   packages/web/src/build/custom-rules-reference.data.ts   rendered into the page's last section
//                                                            by custom-rules-reference.ts
// The site build cannot run core's custom rules entry, so the page reads this copy, and
// scripts/test/sync-custom-rules-reference.test.mjs fails when the copy and teReference() differ.
// Run it after any change to the evaluator's tables (the same change that moves
// `pbiplint reference`).
import { execFileSync } from "node:child_process";
import { realpathSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { teReference } from "@pbiplint/core/custom-rules";

const OUT = "packages/web/src/build/custom-rules-reference.data.ts";

/** The data module's text for a reference, before prettier lays it out. */
export const referenceModule = (
  reference,
) => `// Generated by scripts/sync-custom-rules-reference.mjs from core's teReference(). Do not edit by
// hand: change the evaluator's tables, build core, and rerun
// node scripts/sync-custom-rules-reference.mjs.
import type { TeReference } from "../../../core/src/custom-rules/te/reference.js";

/** What a Tabular Editor rule can use in pbiplint, as the custom rules page's reference shows it. */
export const TE_REFERENCE: TeReference = ${JSON.stringify(reference)};
`;

function main() {
  const reference = teReference();
  writeFileSync(OUT, referenceModule(reference));
  execFileSync("node_modules/.bin/prettier", ["--write", OUT], { stdio: "ignore" });
  console.log(
    `wrote the reference to ${OUT}: ${reference.scopes.length} scopes, ${reference.types.length} object types, ${reference.notRun.length} entries not run`,
  );
}

// Only when run as a script, so a test can import referenceModule without rewriting the data
// file; argv[1] is realpathed for the reason scripts/sync-rule-pages.mjs gives.
if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href)
  main();
